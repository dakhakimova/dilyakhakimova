#!/usr/bin/env node
/* Тире между фамилиями (гайд, пара 119a, решение Дили): фамилии двух разных людей соединяет короткое тире «–» без пробелов —
   «Манн–Уитни», «Колмогоров–Смирнов», «Бенджамини–Хохберг». Ошибка — такая пара через « — », « – », «—» или дефис.
   Фамилии — список PAIRS ниже (в любом падеже по началу слова); новую пару добавляем туда.
   node tools/check-names.js [файл …] — без аргументов: все .html, .js, .json и .md сайта (кроме node_modules и tools).
   Код выхода 1, если что-то нашлось. */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
// [первая фамилия, вторая] — основы без падежного окончания
const PAIRS = [['Манн', 'Уитни'], ['Уилкоксон', 'Манн'], ['Колмогоров', 'Смирнов'], ['Бенджамини', 'Хохберг'], ['Бенджамини', 'Иекутиели'],
  ['Шапиро', 'Уилк'], ['Бокс', 'Мюллер'], ['Бокс', 'Кокс'], ['Уэлч', 'Саттертуэйт'], ['Брайен', 'Флеминг'], ['Марсалья', 'Цанг'],
  ['Абрамовиц', 'Стиган'], ['Бозе', 'Эйнштейн'], ['Бойл', 'Мариотт'], ['Неймана?', 'Пирсон'], ['Крускал', 'Уоллис'], ['Андерсон', 'Дарлинг'],
  ['Коши', 'Буняковск'], ['Коши', 'Шварц'], ['Муавр', 'Лаплас'], ['Берри', 'Эссеен'], ['Кульбак', 'Лейблер'], ['Хорвиц', 'Томпсон'],
  ['Мантел', 'Хензел'], ['Блэк', 'Шоулз'], ['Ньюи', 'Уэст'], ['Дэвидсон', 'Маккиннон']];
const W = '[а-яё]*';
const RX = new RegExp(PAIRS.map(([a, b]) => `${a}${W}(?:[\\u00a0 ]+[—–-][\\u00a0 ]*|[\\u00a0 ]*[—-][\\u00a0 ]*|[\\u00a0 ]*–[\\u00a0 ]+)${b}${W}`).join('|'), 'g');
const SKIP = new Set(['node_modules', 'tools', '.git']);
const walk = d => fs.readdirSync(d, {withFileTypes: true}).flatMap(e => SKIP.has(e.name) ? [] : e.isDirectory() ? walk(path.join(d, e.name))
  : /\.(html|js|json|md)$/.test(e.name) ? [path.relative(ROOT, path.join(d, e.name))] : []);
const files = process.argv.slice(2).length ? process.argv.slice(2) : walk(ROOT);
let bad = 0;
for (const f of files){
  fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').forEach((line, i) => {
    for (const m of line.matchAll(RX)){ bad++; console.log(`${f}:${i + 1}: «${m[0].replace(/ /g, ' ')}» — между фамилиями «–» без пробелов`); }
  });
}
console.log(bad ? `тире между фамилиями: ${bad} ошибок` : 'тире между фамилиями: ок');
process.exit(bad ? 1 : 0);
